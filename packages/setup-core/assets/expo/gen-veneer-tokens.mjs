/*
  Generate global.css + src/veneer-themes.generated.ts from the Veneer tokens you
  installed (@offthegully/veneerui). Run `npm run gen:tokens` after upgrading Veneer
  or to add a theme. Do NOT hand-edit the outputs.

  This reads Veneer's published, server-safe data slice — TOKEN_SCHEMA (every token's
  name/type/bridge/default) and BUILTIN_THEMES — and resolves each theme exactly as
  Veneer's tokenValue() does: `theme.tokens[name] ?? schema default`. No hand-copying,
  so the app can't drift from the Veneer version you installed.
*/
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { TOKEN_SCHEMA, BUILTIN_THEMES } from "@offthegully/veneerui/themes";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const themes = [...BUILTIN_THEMES].sort((a, b) => a.id.localeCompare(b.id));
const resolve = (theme) => TOKEN_SCHEMA.map((t) => [t.name, theme.tokens?.[t.name] ?? t.default]);

// ── global.css ───────────────────────────────────────────────────────────────
function buildGlobalCss() {
  const themeTokens = TOKEN_SCHEMA.filter((t) => t.bridge === "theme");
  const line = (t) => `  --${t.name}: ${t.default};`;
  return [
    // Granular, layered imports — NOT `@import "tailwindcss"`. The bundle inlines the
    // @theme colors, so the utilities lose their var() and can't be swapped at runtime.
    `@import "tailwindcss/theme.css" layer(theme);`,
    `@import "tailwindcss/preflight.css" layer(base);`,
    `@import "tailwindcss/utilities.css";`,
    `@import "nativewind/theme";`,
    ``,
    `/* AUTO-GENERATED by scripts/generate-veneer-tokens.mjs from @offthegully/veneerui.`,
    `   Run \`npm run gen:tokens\` to refresh — do not edit. */`,
    ``,
    `/* @theme → generates the semantic utilities (bg-primary, text-text, rounded-md, …). */`,
    `@theme {`,
    themeTokens.map(line).join("\n"),
    `}`,
    ``,
    `/* :root → runtime defaults for EVERY token, so <VariableContextProvider> can`,
    `   override them. Theme-bridge tokens are intentionally repeated here. */`,
    `:root {`,
    TOKEN_SCHEMA.map(line).join("\n"),
    `}`,
    ``,
  ].join("\n");
}

// ── src/veneer-themes.generated.ts ─────────────────────────────────────────────
function buildThemesTs() {
  const metaTokenEntries = TOKEN_SCHEMA.map(
    (t) => `  ${JSON.stringify(t.name)}: ${JSON.stringify({ bridge: t.bridge, type: t.type })},`,
  ).join("\n");

  const metaEntries = themes
    .map((t) => {
      const meta = { id: t.id, name: t.name };
      if (t.description) meta.description = t.description;
      if (t.tags) meta.tags = t.tags;
      return `  ${JSON.stringify(t.id)}: ${JSON.stringify(meta)},`;
    })
    .join("\n");

  const tokenEntries = themes
    .map((t) => {
      const body = resolve(t)
        .map(([name, value]) => `    ${JSON.stringify(name)}: ${JSON.stringify(value)},`)
        .join("\n");
      return `  ${JSON.stringify(t.id)}: {\n${body}\n  },`;
    })
    .join("\n");

  return [
    `// AUTO-GENERATED by scripts/generate-veneer-tokens.mjs from @offthegully/veneerui — do not edit.`,
    `// Every value is resolved as Veneer's tokenValue() does: override ?? schema default.`,
    `// Run \`npm run gen:tokens\` to refresh.`,
    ``,
    `/** Per-token metadata: \`bridge\` ('theme' = utility, 'root' = var()-only) and \`type\`. */`,
    `export const TOKEN_META = {`,
    metaTokenEntries,
    `} as const;`,
    ``,
    `export type TokenName = keyof typeof TOKEN_META;`,
    `export type TokenType = (typeof TOKEN_META)[TokenName]["type"];`,
    ``,
    `export interface ThemeMeta {`,
    `  id: string;`,
    `  name: string;`,
    `  description?: string;`,
    `  tags?: string[];`,
    `}`,
    ``,
    `export const THEME_META: Record<string, ThemeMeta> = {`,
    metaEntries,
    `};`,
    ``,
    `/** Every builtin Veneer theme, each fully resolved to a flat token → value map. */`,
    `export const THEME_TOKENS = {`,
    tokenEntries,
    `} satisfies Record<string, Record<TokenName, string>>;`,
    ``,
    `export type ThemeId = keyof typeof THEME_TOKENS;`,
    ``,
  ].join("\n");
}

mkdirSync(join(app, "src"), { recursive: true });
writeFileSync(join(app, "global.css"), buildGlobalCss());
writeFileSync(join(app, "src", "veneer-themes.generated.ts"), buildThemesTs());
console.log(`gen:tokens — ${TOKEN_SCHEMA.length} tokens × ${themes.length} themes`);
